let cachedWordSet: Set<string> | null = null;
let cachedArabicMap: Map<string, string> | null = null;

function ensureLoaded(): { wordSet: Set<string>; arabicMap: Map<string, string> } {
  if (cachedWordSet && cachedArabicMap) {
    return { wordSet: cachedWordSet, arabicMap: cachedArabicMap };
  }
  const set = new Set<string>(COMMON_ENGLISH_WORDS);
  const arabicMap = new Map<string, string>(Object.entries(EXTRA_ARABIC_TRANSLATIONS));

  for (const level of LEVELS) {
    const mainUpper = level.mainWord.toUpperCase();
    if (mainUpper.length >= 3) {
      set.add(mainUpper);
      if (!arabicMap.has(mainUpper)) {
        arabicMap.set(mainUpper, level.arabic);
      }
    }
    for (const item of level.extractedWords) {
      const wordUpper = item.word.toUpperCase();
      if (wordUpper.length >= 3) {
        set.add(wordUpper);
        if (!arabicMap.has(wordUpper)) {
          arabicMap.set(wordUpper, item.arabic);
        }
      }
    }
  }
  cachedWordSet = set;
  cachedArabicMap = arabicMap;
  return { wordSet: set, arabicMap };
}

export function warmUpDictionary(): void {
  ensureLoaded();
}

export function isValidEnglishWord(word: string): boolean {
  const normalized = word.trim().toUpperCase();
  if (normalized.length < 3) return false;
  return ensureLoaded().wordSet.has(normalized);
}

export function getWordArabic(word: string): string | null {
  const normalized = word.trim().toUpperCase();
  if (normalized.length < 3) return null;
  return ensureLoaded().arabicMap.get(normalized) ?? null;
}
